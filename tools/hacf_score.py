#!/usr/bin/env python3
"""HACF scoring tool - reference implementation of docs/03-assessment-method.md.

Usage:
    python hacf_score.py sample/people.csv --roles sample/role_profiles.json \
        --out report.md --results results.csv

Input CSV columns: id, department, role, K, A, C, J, R, evidence, scope
(evidence: E1..E5; scope: Self|Team|Organisation|Ecosystem; role/scope optional)

Standard library only. License: MIT (see LICENSE-CODE).
"""
from __future__ import annotations

import argparse
import csv
import json
import sys
from collections import Counter, defaultdict
from dataclasses import dataclass, field
from pathlib import Path

DIMS = ["K", "A", "C", "J", "R"]
DEFAULT_SPEC = Path(__file__).resolve().parent.parent / "assessment" / "hacf-spec.json"


@dataclass
class Result:
    pid: str
    department: str
    role: str
    scores: dict
    evidence: str
    scope: str
    level: int = 0
    level_name: str = ""
    flags: list = field(default_factory=list)
    next_gaps: dict = field(default_factory=dict)
    role_gaps: dict | None = None

    @property
    def profile(self) -> str:
        return "[" + "·".join(f"{d}{self.scores[d]}" for d in DIMS) + "]"

    @property
    def notation(self) -> str:
        return f"HACF L{self.level} {self.profile}  evidence: {self.evidence}  scope: {self.scope}"


class Scorer:
    def __init__(self, spec: dict):
        self.spec = spec
        self.levels = sorted(spec["levels"], key=lambda l: l["level"])
        self.scopes = spec["scopes"]
        self.caps = {k: v["max_level"] for k, v in spec["evidence_levels"].items()}
        self.min_group = spec["org_metrics"]["min_group_size"]

    def _gates_met(self, lvl: dict, s: dict) -> bool:
        return all(s.get(d, 0) >= v for d, v in lvl["gates"].items())

    def _scope_ok(self, lvl: dict, scope: str) -> bool:
        return self.scopes.index(scope) >= self.scopes.index(lvl["min_scope"])

    def score(self, pid, dept, role, scores, evidence, scope) -> Result:
        r = Result(pid, dept, role, scores, evidence, scope)
        cap = self.caps[evidence]
        for lvl in reversed(self.levels):
            if lvl["level"] > cap:
                continue
            if self._gates_met(lvl, scores) and self._scope_ok(lvl, scope):
                r.level, r.level_name = lvl["level"], lvl["name"]
                break
        # flags
        s = scores
        if s["A"] - s["J"] >= 2:
            r.flags.append("RISK-J")
        if max(s["A"], s["C"]) - s["R"] >= 2:
            r.flags.append("RISK-R")
        if s["K"] - s["A"] >= 2:
            r.flags.append("UNTAPPED")
        if r.level < 5:
            nxt = self.levels[r.level + 1]
            gaps = {d: v - s.get(d, 0) for d, v in nxt["gates"].items() if s.get(d, 0) < v}
            r.next_gaps = gaps
            if len(gaps) == 1:
                r.flags.append("CEILING")
        if any(l["level"] > r.level and self._gates_met(l, s) and self._scope_ok(l, scope)
               for l in self.levels):
            r.flags.append("EVIDENCE-CAP")
        if evidence == "E1":
            r.flags.append("PROVISIONAL")
        return r

    @staticmethod
    def role_gap(r: Result, roles: dict) -> dict | None:
        target = roles.get(r.role)
        if target is None:
            return None
        return {d: v - r.scores.get(d, 0) for d, v in target.items()
                if d in DIMS and r.scores.get(d, 0) < v}


def read_people(path: Path) -> list[dict]:
    with open(path, newline="", encoding="utf-8-sig") as f:
        rows = list(csv.DictReader(f))
    out = []
    for i, row in enumerate(rows, start=2):
        try:
            scores = {d: int(row[d]) for d in DIMS}
        except (KeyError, ValueError) as e:
            sys.exit(f"Line {i}: invalid or missing dimension score ({e})")
        for d, v in scores.items():
            if not 0 <= v <= 5:
                sys.exit(f"Line {i}: {d}={v} outside 0..5")
        ev = (row.get("evidence") or "E1").strip().upper()
        sc = (row.get("scope") or "Self").strip().capitalize()
        if sc == "Organization":
            sc = "Organisation"
        out.append(dict(pid=row.get("id", str(i)), dept=row.get("department", "-") or "-",
                        role=row.get("role", "") or "", scores=scores, evidence=ev, scope=sc))
    return out


def org_report(results: list[Result], scorer: Scorer, roles: dict | None) -> str:
    n = len(results)
    mg = scorer.min_group
    lines = ["# HACF Enterprise Report", "",
             f"*Framework version {scorer.spec['version']}. Generated by tools/hacf_score.py.*", ""]
    if n == 0:
        return "\n".join(lines + ["No participants."])
    idx = sum(r.level for r in results) / n / 5 * 100
    flagged = lambda f: sum(f in r.flags for r in results)
    risk = sum(("RISK-J" in r.flags) or ("RISK-R" in r.flags) for r in results)
    e3 = sum(int(r.evidence[1]) >= 3 for r in results)
    l4 = sum(r.level >= 4 for r in results)
    lines += ["## Summary", "", "| Metric | Value |", "|---|---|",
              f"| Participants | {n} |",
              f"| HACF Index | **{idx:.0f}** / 100 |",
              f"| Risk exposure (RISK-J or RISK-R) | {risk / n:.0%} |",
              f"| Untapped potential | {flagged('UNTAPPED') / n:.0%} |",
              f"| One step from next level (CEILING) | {flagged('CEILING') / n:.0%} |",
              f"| Builder density (L4+ per 100) | {l4 / n * 100:.1f} |",
              f"| Evidence quality (E3+) | {e3 / n:.0%} |"]
    with_role = [r for r in results if r.role_gaps is not None]
    if roles is not None and with_role:
        cov = sum(not r.role_gaps for r in with_role) / len(with_role)
        lines.append(f"| Role coverage (meets target profile) | {cov:.0%} of {len(with_role)} with known role |")
    lines += ["", "## Level distribution", "", "| Level | People | Share |", "|---|---|---|"]
    dist = Counter(r.level for r in results)
    for lvl in scorer.levels:
        c = dist.get(lvl["level"], 0)
        lines.append(f"| L{lvl['level']} {lvl['name']} | {c} | {c / n:.0%} |")

    lines += ["", "## Department heat map", "",
              f"Groups smaller than {mg} are suppressed.", "",
              "| Department | n | K | A | C | J | R | L3+ | Risk | Index |",
              "|---|---|---|---|---|---|---|---|---|---|"]
    by_dept = defaultdict(list)
    for r in results:
        by_dept[r.department].append(r)
    for dept in sorted(by_dept):
        grp = by_dept[dept]
        m = len(grp)
        if m < mg:
            lines.append(f"| {dept} | <{mg} | – | – | – | – | – | – | – | – |")
            continue
        means = [sum(r.scores[d] for r in grp) / m for d in DIMS]
        l3 = sum(r.level >= 3 for r in grp) / m
        rk = sum(("RISK-J" in r.flags) or ("RISK-R" in r.flags) for r in grp) / m
        di = sum(r.level for r in grp) / m / 5 * 100
        lines.append(f"| {dept} | {m} | " + " | ".join(f"{x:.1f}" for x in means)
                     + f" | {l3:.0%} | {rk:.0%} | {di:.0f} |")

    gap_counter = Counter()
    for r in with_role:
        for d in (r.role_gaps or {}):
            gap_counter[d] += 1
    if gap_counter:
        lines += ["", "## Most frequent gaps vs. role targets", "", "| Dimension | People below target |", "|---|---|"]
        for d, c in gap_counter.most_common():
            lines.append(f"| {d} — {scorer.spec['dimensions'][d]} | {c} |")

    lines += ["", "## Recommended focus (rule-based)", ""]
    recs = []
    if risk / n >= 0.15:
        recs.append("Risk exposure ≥ 15%: run verification (J) and data-handling (R) training before expanding AI tool access.")
    if dist.get(0, 0) / n >= 0.10:
        recs.append("≥ 10% at L0: launch mandatory AI awareness and rules for all staff.")
    if flagged("UNTAPPED") / n >= 0.10:
        recs.append("Untapped potential ≥ 10%: role-specific workflow clinics give the fastest gains.")
    if l4 / n * 100 < 1:
        recs.append("Builder density below 1 per 100: start a Builder track with candidates flagged CEILING at L3.")
    if e3 / n < 0.5:
        recs.append("Less than half of results at E3+: treat levels as provisional; add practical tasks.")
    lines += [f"- {x}" for x in recs] or ["- No rule-based alerts. Review distribution against role targets."]
    return "\n".join(lines) + "\n"


def main(argv=None):
    p = argparse.ArgumentParser(description="HACF scoring tool")
    p.add_argument("people", type=Path)
    p.add_argument("--spec", type=Path, default=DEFAULT_SPEC)
    p.add_argument("--roles", type=Path, help="role profiles JSON")
    p.add_argument("--out", type=Path, help="write enterprise Markdown report")
    p.add_argument("--results", type=Path, help="write per-person results CSV")
    a = p.parse_args(argv)

    spec = json.loads(a.spec.read_text(encoding="utf-8"))
    roles = json.loads(a.roles.read_text(encoding="utf-8")) if a.roles else None
    scorer = Scorer(spec)
    results = []
    for row in read_people(a.people):
        if row["evidence"] not in scorer.caps:
            sys.exit(f"{row['pid']}: unknown evidence level {row['evidence']}")
        if row["scope"] not in scorer.scopes:
            sys.exit(f"{row['pid']}: unknown scope {row['scope']}")
        r = scorer.score(**row)
        if roles is not None:
            r.role_gaps = Scorer.role_gap(r, roles)
        results.append(r)

    if a.results:
        with open(a.results, "w", newline="", encoding="utf-8") as f:
            w = csv.writer(f)
            w.writerow(["id", "department", "role", "level", "level_name", "profile",
                        "evidence", "scope", "flags", "next_level_gaps", "role_gaps"])
            for r in results:
                w.writerow([r.pid, r.department, r.role, r.level, r.level_name, r.profile,
                            r.evidence, r.scope, " ".join(r.flags),
                            " ".join(f"{d}+{g}" for d, g in r.next_gaps.items()),
                            "" if r.role_gaps is None else " ".join(f"{d}+{g}" for d, g in r.role_gaps.items())])
    report = org_report(results, scorer, roles)
    if a.out:
        a.out.write_text(report, encoding="utf-8")
    if not a.out and not a.results:
        for r in results:
            print(f"{r.pid:>6}  {r.notation}  {' '.join(r.flags)}")
        print()
        print(report)


if __name__ == "__main__":
    main()
